// Builds every site photo from scripts/image-sources.mjs. Run: npm run images
//
//   public/images/<name>-<width>.webp     responsive sizes (480 / 828 / 1200 / 1920)
//   src/lib/images.generated.ts           width, height, focus point and a tiny blur placeholder per photo
//
// Remote sources are downloaded once into .image-cache/ (git-ignored). Local sources are read from the
// path given (relative to the project root). Re-running only rebuilds what changed.

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";
import { sources, widths } from "./image-sources.mjs";

const root = process.cwd();
const cacheDir = join(root, ".image-cache");
const outDir = join(root, "public", "images");
mkdirSync(cacheDir, { recursive: true });
mkdirSync(outDir, { recursive: true });

async function load(src) {
  if (!/^https?:/.test(src)) return readFileSync(join(root, src));
  const file = join(cacheDir, createHash("sha1").update(src).digest("hex").slice(0, 16) + ".jpg");
  if (existsSync(file)) return readFileSync(file);
  const res = await fetch(src, { headers: { "User-Agent": "LLGraniteSiteBuild/1.0" } });
  if (!res.ok) throw new Error(`${res.status} fetching ${src}`);
  const buf = Buffer.from(await res.arrayBuffer());
  writeFileSync(file, buf);
  return buf;
}

const manifest = {};
const keep = new Set();

for (const s of sources) {
  let img = sharp(await load(s.src)).rotate();
  if (s.crop) {
    const m = await img.metadata();
    const W = m.autoOrient?.width ?? m.width;
    const H = m.autoOrient?.height ?? m.height;
    img = sharp(
      await img
        .extract({
          left: Math.round(s.crop.left * W),
          top: Math.round(s.crop.top * H),
          width: Math.round(s.crop.width * W),
          height: Math.round(s.crop.height * H),
        })
        .toBuffer(),
    );
  }
  const base = await img.toBuffer({ resolveWithObject: true });
  const { width, height } = base.info;
  const outWidths = [...new Set(widths.map((w) => Math.min(w, width)))];

  for (const w of outWidths) {
    const file = `${s.name}-${w}.webp`;
    keep.add(file);
    await sharp(base.data).resize({ width: w }).webp({ quality: w > 1000 ? 68 : 72, effort: 5 }).toFile(join(outDir, file));
  }

  const tiny = await sharp(base.data).resize(16).blur(0.6).webp({ quality: 40 }).toBuffer();
  manifest[s.name] = {
    width: outWidths.at(-1),
    height: Math.round((height / width) * outWidths.at(-1)),
    widths: outWidths,
    focus: s.focus ?? "50% 50%",
    blur: `data:image/webp;base64,${tiny.toString("base64")}`,
  };
  console.log(`✓ ${s.name} (${outWidths.join(", ")})`);
}

// Clear out files for photos that were removed or renamed.
for (const f of readdirSync(outDir)) if (f.endsWith(".webp") && !keep.has(f)) rmSync(join(outDir, f));

const ts = `// Generated by scripts/build-images.mjs. Do not edit by hand: change scripts/image-sources.mjs and run \`npm run images\`.

export const images = ${JSON.stringify(manifest, null, 2)} as const;

export type ImageName = keyof typeof images;
`;
writeFileSync(join(root, "src", "lib", "images.generated.ts"), ts);
console.log(`\nWrote ${keep.size} files to public/images and src/lib/images.generated.ts`);
